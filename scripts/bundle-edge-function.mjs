// Inlines an edge function's ../_shared/* imports into one self-contained file.
//
// The Supabase dashboard's function editor only deploys files inside the
// function's own folder, so a function that imports from ../_shared cannot be
// pasted into it. The CLI has no such limit — this exists purely so the
// functions can be deployed by someone without a terminal.
//
// The repo keeps _shared as the single source of truth; what this prints is a
// build artifact. Re-run it after changing either the function or the shared
// files, or the pasted copy goes stale.
//
//   node scripts/bundle-edge-function.mjs read-snip [outDir]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const FUNCTIONS_DIR = resolve('supabase/functions')

// import ... from './x.ts' — only relative paths are inlined; npm: and jsr:
// specifiers are left for the Deno runtime to fetch as usual.
//
// The clause before `from` must not cross a newline. Allowing it to would let
// the match start at an earlier `import` line and swallow it whole — which it
// did, silently dropping the createClient import and producing a bundle that
// looked fine and could not run.
const RELATIVE_IMPORT = /^import\s+(?:type\s+)?[^\n]*?\s+from\s+['"](\.[^'"]+)['"]\s*;?\s*$/gm
const BARE_IMPORT = /^import\s+['"][^'"]+['"]\s*;?\s*$/gm

function collect(entry, seen, hoisted) {
  const source = readFileSync(entry, 'utf8')
  let body = source
  const inlined = []

  for (const match of source.matchAll(RELATIVE_IMPORT)) {
    const target = resolve(dirname(entry), match[1])
    body = body.replace(match[0], '')
    if (seen.has(target)) continue
    seen.add(target)
    inlined.push(collect(target, seen, hoisted))
  }

  // Non-relative imports move to the top of the bundle, deduplicated: two files
  // both importing createClient must not emit it twice.
  for (const line of body.split('\n')) {
    if (/^import\s/.test(line) && !/from\s+['"]\./.test(line)) hoisted.add(line.trim())
  }
  body = body
    .split('\n')
    .filter((line) => !(/^import\s/.test(line) && !/from\s+['"]\./.test(line)))
    .join('\n')
    .replace(BARE_IMPORT, '')

  // Everything lands in one module scope, so `export` is meaningless and
  // `export interface` would be a syntax error at the top level of a script.
  body = body.replace(/^export\s+(?=(interface|type|const|function|async|class|let)\b)/gm, '')

  return [...inlined, body].join('\n')
}

const name = process.argv[2]
if (!name) {
  console.error('usage: node scripts/bundle-edge-function.mjs <function-name> [outDir]')
  process.exit(1)
}

const entry = join(FUNCTIONS_DIR, name, 'index.ts')
const hoisted = new Set()
const merged = collect(entry, new Set([entry]), hoisted)

const header = `// ${name} — self-contained build for the Supabase dashboard editor.
//
// Generated by scripts/bundle-edge-function.mjs from
// supabase/functions/${name}/index.ts and supabase/functions/_shared/.
// Edit those, not this: re-running the script overwrites this file.
`

const output = [header, [...hoisted].join('\n'), merged.replace(/\n{3,}/g, '\n\n').trim(), ''].join('\n')

const outDir = process.argv[3]
if (outDir) {
  mkdirSync(outDir, { recursive: true })
  const path = join(outDir, `${name}.ts`)
  writeFileSync(path, output)
  console.log(`${path} (${output.split('\n').length} lines)`)
} else {
  process.stdout.write(output)
}
